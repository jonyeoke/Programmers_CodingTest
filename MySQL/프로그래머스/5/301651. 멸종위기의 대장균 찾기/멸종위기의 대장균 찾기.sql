WITH RECURSIVE COUNT_GEN AS(

SELECT ID, 1 AS GEN
FROM ECOLI_DATA
WHERE PARENT_ID IS NULL

UNION ALL

SELECT C.ID, P.GEN + 1
FROM ECOLI_DATA C JOIN COUNT_GEN P ON C.PARENT_ID = P.ID
)

SELECT COUNT(*) AS COUNT, GEN
FROM COUNT_GEN
WHERE ID NOT IN (
    SELECT PARENT_ID FROM ECOLI_DATA WHERE PARENT_ID IS NOT NULL
)
GROUP BY GEN
ORDER BY GEN;